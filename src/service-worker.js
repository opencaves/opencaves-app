import { setCacheNameDetails, clientsClaim } from 'workbox-core'
import { precacheAndRoute, createHandlerBoundToURL } from 'workbox-precaching'
import { registerRoute } from 'workbox-routing'
import { StaleWhileRevalidate, CacheFirst } from 'workbox-strategies'
import { ExpirationPlugin } from 'workbox-expiration'
import { CacheableResponsePlugin } from 'workbox-cacheable-response'
import * as googleAnalytics from 'workbox-google-analytics'

const CACHE_PREFIX = 'oc'
const CACHE_SUFFIX = 'v1'

function cacheName(name) {
  return `${CACHE_PREFIX}-${name}-${CACHE_SUFFIX}`
}

setCacheNameDetails({
  prefix: CACHE_PREFIX,
  suffix: CACHE_SUFFIX,
  precache: 'app',
  googleAnalytics: 'analytics'
})

clientsClaim()

googleAnalytics.initialize({
  parameterOverrides: {
    network_status: 'offline'
  }
})

// Precache all of the assets generated by your build process.
// Their URLs are injected into the manifest variable below.
// This variable must be present somewhere in your service worker file,
// even if you decide not to use precaching. See https://cra.link/PWA
const manifest = self.__WB_MANIFEST
// console.log('manifest: %o', manifest)
precacheAndRoute(manifest)

// Set up App Shell-style routing, so that all navigation requests
// are fulfilled with your index.html shell. Learn more at
// https://developers.google.com/web/fundamentals/architecture/app-shell
const fileExtensionRegexp = new RegExp('/[^/?]+\\.[^/]+$')
registerRoute(
  // Return false to exempt requests from being fulfilled by index.html.
  ({ request, url }) => {
    // If this isn't a navigation, skip.
    if (request.mode !== 'navigate') {
      return false
    }

    // If this is a URL that starts with /_, skip.
    if (url.pathname.startsWith('/_')) {
      return false
    }

    // If this looks like a URL for a resource, because it contains // a file extension, skip.
    if (url.pathname.match(fileExtensionRegexp)) {
      return false
    }

    // Return true to signal that we want to use the handler.
    return true
  },
  createHandlerBoundToURL(`${import.meta.env.BASE_URL}index.html`)
)

// An example runtime caching route for requests that aren't handled by the
// precache, in this case same-origin .png requests like those from in public/

const imagesRegEx = /\.(png|jpg|ico|webp)($|\?|#)/
registerRoute(
  // Add in any other file extensions or routing criteria as needed.
  ({ url }) => url.origin === self.location.origin && imagesRegEx.test(url.pathname),
  new StaleWhileRevalidate({
    cacheName: cacheName('images')
  })
)
// Uploaded maps (images/PDFs), fetched through Firebase Storage download
// URLs. (url.origin never has a trailing slash - comparing against one would
// never match.)
registerRoute(
  ({ url }) => url.origin === 'https://firebasestorage.googleapis.com' && url.pathname.startsWith('/v0/b/opencaves.appspot.com'),
  new StaleWhileRevalidate({
    cacheName: cacheName('images')
  })
)

// Cave pictures and their resized thumbnails, served as public objects from
// the bucket (CaveAsset.js). Each URL's content never changes (uploaded with
// an immutable Cache-Control), so cache-first is safe. The app loads them in
// CORS mode (crossOrigin="anonymous", bucket CORS in storage.cors.json), so
// entries count against quota at their real size. Opaque (status 0)
// responses are still accepted for any <img> without crossOrigin. The cache
// name changed when CORS mode came in, so no earlier opaque entry is ever
// served to a CORS request (which the browser would reject).
registerRoute(
  ({ url }) => url.origin === 'https://storage.googleapis.com' && url.pathname.startsWith('/opencaves.appspot.com/'),
  new CacheFirst({
    cacheName: cacheName('cave-images-cors'),
    plugins: [
      new CacheableResponsePlugin({ statuses: [0, 200] }),
      new ExpirationPlugin({ maxEntries: 3000, maxAgeSeconds: 90 * 24 * 60 * 60, purgeOnQuotaError: true }),
    ],
  })
)

registerRoute(
  ({ url }) => url.origin === 'https://maps.googleapis.com',
  new StaleWhileRevalidate({
    cacheName: cacheName('google-maps-api')
  })
)

registerRoute(
  ({ url }) => url.origin === 'https://api.mapbox.com',
  new StaleWhileRevalidate({
    cacheName: cacheName('mapbox-api')
  })
)

registerRoute(
  ({ url }) => url.origin === 'https://www.googletagmanager.com',
  new StaleWhileRevalidate({
    cacheName: cacheName('analytics')
  })
)

